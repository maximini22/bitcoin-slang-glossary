def card_single(src,out):
    c=Image.open(src).convert("RGB").resize((560,560),Image.LANCZOS)
    im=Image.new("RGB",(1200,630),BG); im.paste(c,(320,35)); im.save(out,quality=88)
def card_fan(srcs,out):
    n=len(srcs); L=Image.new("RGBA",(2400,1400),(0,0,0,0))
    for i,s in enumerate(srcs):
        c=Image.open(s).convert("RGBA").resize((400,400),Image.LANCZOS)
        k=i-(n-1)/2; r=c.rotate(-k*8,expand=True,resample=Image.BICUBIC)
        L.alpha_composite(r,(int(1200-r.width/2+k*150),int(700-r.height/2+abs(k)*12)))
    L=L.crop(L.getbbox()); L.thumbnail((1120,570))
    im=Image.new("RGBA",(1200,630),BG+(255,)); im.alpha_composite(L,((1200-L.width)//2,(630-L.height)//2))
    im.convert("RGB").save(out,quality=88)
def clip(s,n=158):
    s=re.sub(r"\s+"," ",s).strip()
    if len(s)<=n: return s
    s=s[:n-1].rsplit(" ",1)[0].rstrip(",;:—-·")
    return s+"…"
def block(title,desc,url,img,typ,alt):
    e=lambda v: html.escape(v,quote=True)
    return "\n".join(["  <!-- meta:start (generated by tools/build_meta.py) -->",
    f"  <title>{e(title)}</title>",
    f'  <meta name="description" content="{e(desc)}" />',
    f'  <link rel="canonical" href="{url}" />',
    f'  <meta property="og:title" content="{e(title)}" />',
    f'  <meta property="og:description" content="{e(desc)}" />',
    f'  <meta property="og:image" content="{img}" />',
    '  <meta property="og:image:width" content="1200" />',
    '  <meta property="og:image:height" content="630" />',
    f'  <meta property="og:image:alt" content="{e(alt)}" />',
    f'  <meta property="og:url" content="{url}" />',
    f'  <meta property="og:type" content="{typ}" />',
    '  <meta property="og:site_name" content="BitcoinSlang.com" />',
    '  <meta name="twitter:card" content="summary_large_image" />',
    f'  <meta name="twitter:site" content="{HANDLE}" />',
    f'  <meta name="twitter:creator" content="{HANDLE}" />',
    f'  <meta name="twitter:title" content="{e(title)}" />',
    f'  <meta name="twitter:description" content="{e(desc)}" />',
    f'  <meta name="twitter:image" content="{img}" />',
    f'  <meta name="twitter:image:alt" content="{e(alt)}" />',
    "  <!-- meta:end -->"])
STRIP=re.compile(r'^\s*(<title>.*</title>|<meta (name|property)="(description|og:[^"]*|twitter:[^"]*)"[^>]*>|<link rel="canonical"[^>]*>|<!-- meta:(start|end).*-->|[^<\s][^<]*"\s*/>)\s*$')
def apply(path,blk):
    src=open(path,encoding="utf-8").read()
    head,rest=src.split("</head>",1)
    lines=[l for l in head.split("\n") if not STRIP.match(l)]
    i=max(k for k,l in enumerate(lines) if re.search(r'name="(viewport|robots)"',l))
    lines.insert(i+1,blk)
    open(path,"w",encoding="utf-8").write("\n".join(lines)+"</head>"+rest)
